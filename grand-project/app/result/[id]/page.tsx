// app/result/[id]/page.tsx

import dbConnect from "@/lib/mongodb";
import PitchDocument, { IPitchDocument } from "@/models/PitchDocument";
import { notFound } from "next/navigation";
import { ResultView } from "./ResultView"; // We'll create this client component next

// This is the correct type definition for a Next.js dynamic page's props.
// This is the line that fixes the primary build error.
type ResultPageProps = {
  params: { id: string };
};

// This function fetches the pitch data (including the n8n response) from MongoDB.
async function getPitchData(pitchId: string): Promise<IPitchDocument | null> {
  await dbConnect();
  const pitch = await PitchDocument.findOne({ pitchId: pitchId }).lean();
  if (!pitch) {
    return null;
  }
  // We serialize the data to safely pass it from a Server Component to a Client Component.
  return JSON.parse(JSON.stringify(pitch));
}

// This is the main server component for the page.
export default async function ResultPage({ params }: ResultPageProps) {
  const pitchData = await getPitchData(params.id);

  if (!pitchData) {
    notFound(); // Show a 404 page if the pitch ID is invalid.
  }

  return (
    <main className="container mx-auto p-4 md:p-8">
      <h1 className="text-3xl font-bold mb-2">Your Generated Pitch</h1>
      <p className="text-muted-foreground mb-6">Review the pitch generated by our AI service (via n8n).</p>
      
      {/* We pass the fetched data to a client component to handle user actions like saving or deleting. */}
      <ResultView pitch={pitchData} />
    </main>
  );
}